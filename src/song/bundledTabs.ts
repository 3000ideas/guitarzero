export const BUNDLED_TABS: readonly BundledTab[] = [{ id: 'last-horizon-punteo', title: 'Last Horizon (punteo)', artist: 'Brian May', version: 1, tab: LAST_HORIZON }];

/** The `source` of a tab song: only the headers (the tab itself lives in `StoredSong.tab`). */
export function tabSongSource(title: string, artist: string): string {
  return `title: ${title}\nartist: ${artist}\ntempo: 100\ntime: 4/4\n`;
}

const flagName = (b: BundledTab): string => `bundledTab:${b.id}:v${b.version}`;

/** Creates the library entries of the bundled tablatures that are still missing. */
export function installBundledTabs(tabs: readonly BundledTab[] = BUNDLED_TABS): void {
  for (const b of tabs) {
    if (getSong(b.id) || getFlag(flagName(b))) continue; // there already, or deleted by the user: leave it
    const entry: StoredSong = { id: b.id, title: b.title, artist: b.artist, source: tabSongSource(b.title, b.artist), updatedAt: 0, tab: b.tab };
    saveSong(entry);
    setFlag(flagName(b));
  }
}
